create table if not exists public.spaces (
  id bigint generated by default as identity primary key,
  host_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  location text not null,
  type text not null check (type in ('Bedspace', 'Private room')),
  description text not null,
  monthly_rent numeric(10, 2) not null check (monthly_rent > 0),
  cover_photo_url text,
  latitude double precision,
  longitude double precision,
  status text not null default 'published' check (status in ('draft', 'published')),
  created_at timestamptz not null default now()
);

alter table public.spaces add column if not exists latitude double precision;
alter table public.spaces add column if not exists longitude double precision;
alter table public.spaces drop constraint if exists spaces_coordinate_pair_check;
alter table public.spaces add constraint spaces_coordinate_pair_check
  check (
    (latitude is null and longitude is null)
    or (
      latitude is not null
      and longitude is not null
      and latitude between -90 and 90
      and longitude between -180 and 180
    )
  );

create index if not exists spaces_host_id_idx on public.spaces(host_id);
create index if not exists spaces_status_idx on public.spaces(status);

create table if not exists public.floors (
  id bigint generated by default as identity primary key,
  space_id bigint not null references public.spaces(id) on delete cascade,
  name text not null,
  photo_url text,
  created_at timestamptz not null default now(),
  unique (id, space_id)
);

create table if not exists public.rooms (
  id bigint generated by default as identity primary key,
  space_id bigint not null,
  floor_id bigint not null,
  name text not null,
  photo_url text,
  monthly_rent numeric(10, 2) check (monthly_rent is null or monthly_rent > 0),
  amenities text[] not null default '{}',
  house_rules text[] not null default '{}',
  maintenance text[] not null default '{}',
  grid_rows integer not null default 1 check (grid_rows > 0),
  grid_columns integer not null default 1 check (grid_columns > 0),
  door_row integer,
  door_column integer,
  created_at timestamptz not null default now(),
  unique (id, space_id),
  foreign key (floor_id, space_id) references public.floors(id, space_id) on delete cascade,
  check (
    (door_row is null and door_column is null)
    or (
      door_row is not null
      and door_column is not null
      and door_row between 1 and grid_rows
      and door_column between 1 and grid_columns
    )
  )
);

create table if not exists public.bedspaces (
  id bigint generated by default as identity primary key,
  space_id bigint not null,
  room_id bigint not null,
  name text not null,
  price numeric(10, 2) not null check (price > 0),
  row integer not null check (row > 0),
  column_index integer not null check (column_index > 0),
  photo_url text,
  amenities text[] not null default '{}',
  house_rules text[] not null default '{}',
  maintenance text[] not null default '{}',
  created_at timestamptz not null default now(),
  foreign key (room_id, space_id) references public.rooms(id, space_id) on delete cascade
);

create or replace function public.owns_space(p_space_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.spaces
    where id = p_space_id and host_id = auth.uid()
  );
$$;

create or replace function public.can_read_space(p_space_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.spaces
    where id = p_space_id
      and (status = 'published' or host_id = auth.uid())
  );
$$;

create or replace function public.can_manage_space_photo(p_name text)
returns boolean
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  photo_space_id bigint;
begin
  if p_name !~ '^[0-9a-f-]{36}/[0-9]+/.+$'
    or split_part(p_name, '/', 1) <> auth.uid()::text then
    return false;
  end if;

  photo_space_id := split_part(p_name, '/', 2)::bigint;
  return public.owns_space(photo_space_id);
end;
$$;

grant execute on function public.owns_space(bigint) to anon, authenticated;
grant execute on function public.can_read_space(bigint) to anon, authenticated;
grant execute on function public.can_manage_space_photo(text) to authenticated;

